module bus_decoder (
    input wire [31:0] addr,

    output wire cs_bram,
    output wire cs_vga,
    output wire cs_gpio
);


    // =========================================================
    // MAIN RAM
    //
    // 0x00000000 - 0x00001FFF
    // =========================================================

    assign cs_bram =
        (addr >= 32'h00000000) &&
        (addr <= 32'h00001FFF);


    // =========================================================
    // VGA FRAMEBUFFER
    //
    // 0x80000000 - 0x80001FFF
    // =========================================================

    assign cs_vga =
        (addr >= 32'h80000000) &&
        (addr <= 32'h80001FFF);


    // =========================================================
    // GPIO
    //
    // 0x80003000
    // =========================================================

    assign cs_gpio =
        (addr == 32'h80003000);


endmodule